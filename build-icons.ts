// Builds src/icons/icons.generated.ts from the SVGs in icons/.
// Run with `npm run icons`. The SVGs are exported from Figma; never edit them by hand.

import fs from 'node:fs';
import path from 'node:path';

const ICONS = 'icons';
const OUTPUT = 'src/icons/icons.generated.ts';

// Colors an icon may use, so it always takes the text color around it.
// Nav icons also use --icon-accent-* variables, which fall back to currentColor.
const ALLOWED_COLOR = /^(none|currentColor|var\(--icon-accent-[a-z-]+, currentColor\))$/;

const problems: string[] = [];

function svgFiles(dir: string): string[] {
  return fs
    .readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter((file) => file.endsWith('.svg'))
    .sort();
}

function readIcon(file: string) {
  // "nav/portfolio.svg" → "nav/portfolio", matching the Figma name without "icon/"
  const name = file.replace(/\.svg$/, '').split(path.sep).join('/');
  const svg = fs.readFileSync(path.join(ICONS, file), 'utf8');

  const root = /<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  const viewBox = root && /\bviewBox="([^"]+)"/.exec(root[1])?.[1];
  if (!root || !viewBox) {
    problems.push(`${file}: no <svg> with a viewBox`);
    return null;
  }

  // The inner markup, without the <metadata> block (content credentials) and
  // the line breaks between elements
  const markup = root[2]
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
    .replace(/>\s+</g, '><')
    .trim();

  if (!/^[a-z0-9-]+(\/[a-z0-9-]+)*$/.test(name)) problems.push(`${file}: names are lowercase with dashes`);
  if (/<script\b|\son[a-z]+=/i.test(markup)) problems.push(`${file}: contains a script or event handler`);
  for (const [, attribute, value] of markup.matchAll(/\s(fill|stroke)="([^"]*)"/g)) {
    if (!ALLOWED_COLOR.test(value)) problems.push(`${file}: ${attribute}="${value}" should be currentColor or var(--icon-accent-…, currentColor)`);
  }

  return { name, viewBox, markup };
}

const icons = svgFiles(ICONS).map(readIcon);

if (problems.length > 0) {
  for (const problem of problems) console.error(problem);
  process.exit(1);
}

const entries = icons
  .filter((icon) => icon !== null)
  .map(({ name, viewBox, markup }) => `  ${JSON.stringify(name)}: {\n    viewBox: ${JSON.stringify(viewBox)},\n    markup: ${JSON.stringify(markup)},\n  },`)
  .join('\n');

const output = `// Verity icons
// Generated by build-icons.ts from icons/. Don't edit by hand: re-export the
// icons from Figma and run \`npm run icons\`.

export const ICONS = {
${entries}
} as const;

export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, output);
console.log(`Wrote ${OUTPUT} (${icons.length} icons)`);
